package com.ngdstudio.mindimania.spider

import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File
import java.util.concurrent.Executors
import java.util.concurrent.atomic.AtomicInteger

/**
 * Rebuilds SpiderDeals.kt (the graded 2- and 4-suit deals). Not part of the normal test run; takes a while:
 *   SPIDER_GENERATE=1 ./gradlew :app:testDebugUnitTest --rerun --tests '*SpiderDealGenerator*'
 * For each suit count it solves candidate seeds with [SpiderDealSolver] until it has twice [keep] winnable deals, then
 * keeps the hardest half (most solver effort): every kept deal can be won, and none is an easy one.
 */
class SpiderDealGenerator {
    private val keep = mapOf(2 to 200, 4 to 150)

    @Test
    fun generate() {
        assumeTrue(System.getenv("SPIDER_GENERATE") != null)
        val lists = keep.mapValues { (suits, n) -> grade(suits, n) }
        val out = StringBuilder()
        out.appendLine("package com.ngdstudio.mindimania.spider")
        out.appendLine()
        out.appendLine("// GENERATED by SpiderDealGenerator (test sources). Do not edit by hand.")
        out.appendLine()
        out.appendLine("/** Hard but winnable deal seeds for SpiderEngine.newGame, graded by SpiderDealSolver. */")
        out.appendLine("internal object SpiderDeals {")
        for ((suits, seeds) in lists) {
            out.appendLine("    /** ${seeds.size} graded ${suits}-suit deals. */")
            out.appendLine("    val SUITS_$suits = longArrayOf(")
            seeds.chunked(4).forEach { row -> out.appendLine("        " + row.joinToString(", ") { "${it}L" } + ",") }
            out.appendLine("    )")
        }
        out.appendLine("}")
        File("src/main/java/com/ngdstudio/mindimania/spider/SpiderDeals.kt").writeText(out.toString())
    }

    private fun grade(suits: Int, n: Int): List<Long> {
        val want = n * 2
        val found = java.util.Collections.synchronizedList(ArrayList<Pair<Long, Int>>())
        val tries = AtomicInteger()
        val pool = Executors.newFixedThreadPool(6)
        val t0 = System.currentTimeMillis()
        val jobs = (0 until 6).map { w ->
            pool.submit {
                var i = w
                while (found.size < want && i < 20_000) {
                    val seed = (suits * 1_000_003L + i) * -0x61c8864680b583ebL
                    val r = SpiderDealSolver.solve(SpiderEngine.newGame(suits, seed))
                    tries.incrementAndGet()
                    if (r.won) found += seed to r.effort
                    i += 6
                }
            }
        }
        jobs.forEach { it.get() }
        pool.shutdown()
        val sorted = found.toList().sortedByDescending { it.second }
        val kept = sorted.take(n)
        println("SPIDER suits=$suits tried=${tries.get()} winnable=${found.size} keep=${kept.size} " +
            "effort min=${sorted.lastOrNull()?.second} median=${sorted.getOrNull(sorted.size / 2)?.second} " +
            "cutoff=${kept.lastOrNull()?.second} max=${sorted.firstOrNull()?.second} time=${(System.currentTimeMillis() - t0) / 1000}s")
        return kept.map { it.first }.sorted()
    }
}
